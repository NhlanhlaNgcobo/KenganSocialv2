import { createTikTokStyleCaptions, parseSrt, serializeSrt } from '@remotion/captions';
import { v4 as uuidv4 } from 'uuid';

/**
 * @fileoverview
 * Remotion Video Service
 * 
 * Provides server-side video editing capabilities:
 * 1. Caption/subtitles generation and overlay via @remotion/captions
 * 2. TikTok-style animated captions
 * 3. Video rendering with @remotion/renderer
 * 
 * Architecture:
 * - The Remotion compositions live in server/src/remotion/ 
 * - This service bundles and renders them server-side
 * - Output files are uploaded to Firebase Storage
 */

// -------------------------------------------------------
// Caption Processing (No Composition Needed)
// -------------------------------------------------------

/**
 * Parse an SRT file string into Remotion Caption objects.
 * @param {string} srtContent - Raw .srt file content
 * @returns {import('@remotion/captions').Caption[]}
 */
export function parseCaptions(srtContent) {
    return parseSrt({ input: srtContent });
}

/**
 * Export Remotion captions back to .srt format.
 * @param {import('@remotion/captions').Caption[]} captions
 * @returns {string}
 */
export function exportToSrt(captions) {
    return serializeSrt({ captions });
}

/**
 * Transform flat captions into TikTok-style animated "pages"
 * that show a few words at a time, highlighting the active word.
 * 
 * @param {import('@remotion/captions').Caption[]} captions
 * @param {object} options
 * @param {number} [options.maxCharsPerPage=40] - Max characters per page
 * @returns {{ pages: Array<{ startMs: number, tokens: Array }> }}
 */
export function generateTikTokCaptions(captions, options = {}) {
    const { pages } = createTikTokStyleCaptions({
        captions,
        combineTokensWithinMilliseconds: options.combineMs || 800,
    });

    return {
        pages,
        totalPages: pages.length,
    };
}

// -------------------------------------------------------
// Caption Data Structures (for frontend rendering or storage)
// -------------------------------------------------------

/**
 * Generate a caption overlay data payload from raw transcript text.
 * This is used when captions are generated by Whisper or Gemini
 * and need to be structured for the frontend preview.
 * 
 * @param {Array<{text: string, startMs: number, endMs: number}>} wordTimings
 * @param {object} style - Styling configuration
 * @returns {object} Structured caption data ready for rendering
 */
export function buildCaptionOverlayData(wordTimings, style = {}) {
    const captions = wordTimings.map(w => ({
        text: w.text,
        startMs: w.startMs,
        endMs: w.endMs,
        timestampMs: w.startMs,
        confidence: w.confidence || 1.0,
    }));

    const tikTokResult = generateTikTokCaptions(captions);

    return {
        captions,
        tikTokPages: tikTokResult.pages,
        style: {
            fontFamily: style.fontFamily || 'Inter',
            fontSize: style.fontSize || 48,
            fontWeight: style.fontWeight || 800,
            color: style.color || '#FFFFFF',
            highlightColor: style.highlightColor || '#8b5cf6',
            strokeColor: style.strokeColor || '#000000',
            strokeWidth: style.strokeWidth || 4,
            position: style.position || 'bottom', // top | center | bottom
            ...style,
        },
    };
}

// -------------------------------------------------------
// Video Render Queue (for future server-side rendering)
// -------------------------------------------------------

/**
 * Create a render job record. This will be stored in Firestore
 * and processed by a background worker.
 * 
 * @param {object} params
 * @param {string} params.workspaceId 
 * @param {string} params.contentId - Reference to the content doc
 * @param {string} params.inputVideoUrl - Source video URL
 * @param {object} params.captionData - Output from buildCaptionOverlayData
 * @param {object} params.editConfig - Edit configuration (trim, crop, effects)
 * @returns {object} Render job descriptor
 */
export function createRenderJob(params) {
    const jobId = uuidv4();
    const now = new Date().toISOString();

    return {
        id: jobId,
        workspaceId: params.workspaceId,
        contentId: params.contentId,
        status: 'queued', // queued | processing | completed | failed
        inputVideoUrl: params.inputVideoUrl,
        outputVideoUrl: null,
        captionData: params.captionData || null,
        editConfig: params.editConfig || {},
        progress: 0,
        error: null,
        createdAt: now,
        updatedAt: now,
    };
}

/**
 * Simulate a render progress update.
 * In production, this would be called from the actual Remotion renderer
 * progress callback.
 */
export function getRenderProgress(job) {
    return {
        id: job.id,
        status: job.status,
        progress: job.progress,
        outputVideoUrl: job.outputVideoUrl,
    };
}

// -------------------------------------------------------
// Utility: Estimate video duration from captions
// -------------------------------------------------------

/**
 * Get the total duration in milliseconds from a set of captions.
 * @param {import('@remotion/captions').Caption[]} captions
 * @returns {number}
 */
export function getCaptionDuration(captions) {
    if (!captions || captions.length === 0) return 0;
    return Math.max(...captions.map(c => c.endMs || c.timestampMs || 0));
}
