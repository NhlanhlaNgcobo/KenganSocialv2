// Run from the repository root: node scripts/build-legal.mjs
// Writes the Terms, Privacy Policy and Data Deletion pages as static HTML from
// client/src/legal/legal-content.js, so they read without JavaScript (platform reviewers and
// crawlers): client/public/legal/*.html (website) and server/public/legal/*.html (API host).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { POLICIES } from '../client/src/legal/legal-content.js';
import { COMPANY } from '../client/src/legal/company.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = [path.join(root, 'client/public/legal'), path.join(root, 'server/public/legal')];
const FILES = { terms: 'terms.html', privacy: 'privacy.html', 'data-deletion': 'data-deletion.html' };

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
function inline(text) {
    let out = '';
    let last = 0;
    const re = /\[([^\]]+)\]\(([^)]+)\)|\*\*([^*]+)\*\*/g;
    let m;
    while ((m = re.exec(text))) {
        out += esc(text.slice(last, m.index));
        if (m[3]) out += `<strong>${esc(m[3])}</strong>`;
        else {
            const href = m[2].startsWith('/') ? `${COMPANY.website}${m[2]}` : m[2];
            out += `<a href="${esc(href)}">${esc(m[1])}</a>`;
        }
        last = m.index + m[0].length;
    }
    return out + esc(text.slice(last));
}
function block(b) {
    if (b.p) return `<p>${inline(b.p)}</p>`;
    if (b.ul) return `<ul>${b.ul.map((i) => `<li>${inline(i)}</li>`).join('')}</ul>`;
    if (b.table) return `<table><thead><tr>${b.table.head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${b.table.rows.map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
    return '';
}

export function renderPolicy(key) {
    const p = POLICIES[key];
    const nav = Object.entries(FILES)
        .map(([k]) => `<a href="${COMPANY.website}/${k}"${k === key ? ' aria-current="page"' : ''}>${esc(POLICIES[k].title)}</a>`)
        .join(' · ');
    return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(p.title)} | ${esc(COMPANY.brand)}</title>
<meta name="description" content="${esc(p.intro)}">
<!-- Generated by scripts/build-legal.mjs from client/src/legal/legal-content.js. Do not edit. -->
<style>
body{margin:0;background:#f7f7fb;color:#1d1a33;font:16px/1.7 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
main{max-width:860px;margin:0 auto;padding:24px 16px 64px}
header{display:flex;flex-wrap:wrap;gap:8px 16px;align-items:baseline;justify-content:space-between;margin-bottom:24px}
header strong{font-size:1.2rem}
nav a{color:#5b3fd6}
h1{font-size:2rem;line-height:1.2;margin:0 0 4px}h2{font-size:1.2rem;margin:28px 0 8px}
a{color:#5b3fd6}table{border-collapse:collapse;width:100%;font-size:.92rem}th,td{border:1px solid #d9d6e8;padding:8px;text-align:left;vertical-align:top}
.updated{color:#5f5b78;margin:0 0 16px}
footer{margin-top:40px;color:#5f5b78;font-size:.9rem}
</style>
</head>
<body>
<main>
<header><strong><a href="${COMPANY.website}" style="color:inherit;text-decoration:none">${esc(COMPANY.brand)}</a></strong><nav>${nav}</nav></header>
<h1>${esc(p.title)}</h1>
<p class="updated">Last updated: ${esc(p.updated)}</p>
<p>${inline(p.intro)}</p>
${p.sections.map((s) => `<section id="${s.id}"><h2>${esc(s.heading)}</h2>${s.blocks.map(block).join('')}</section>`).join('\n')}
${key === 'data-deletion' ? `<section id="status"><h2>Check a deletion request</h2><p>Open <a href="${COMPANY.website}/data-deletion/status">${esc(COMPANY.website.replace('https://', ''))}/data-deletion/status</a> and enter your confirmation code.</p></section>` : ''}
<footer>${esc(COMPANY.legalName)} · <a href="mailto:${COMPANY.emails.privacy}">${COMPANY.emails.privacy}</a></footer>
</main>
</body>
</html>
`;
}

export function buildAll() {
    const written = [];
    for (const dir of OUT) {
        fs.mkdirSync(dir, { recursive: true });
        for (const [key, file] of Object.entries(FILES)) {
            fs.writeFileSync(path.join(dir, file), renderPolicy(key));
            written.push(path.relative(root, path.join(dir, file)));
        }
    }
    return written;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    for (const f of buildAll()) console.log(`wrote ${f}`);
}
