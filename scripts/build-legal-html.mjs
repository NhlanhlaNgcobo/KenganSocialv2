// Builds static HTML copies of the legal documents from client/src/content/legal.js, so the
// URLs given to Meta, TikTok and Google work without JavaScript:
//   client/public/<slug>/index.html  → https://kengansocial.co.za/<slug>
//   server/public/legal/<slug>.html  → served by the API at /<slug>
// Usage: node scripts/build-legal-html.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { COMPANY, LEGAL_DOCS, linkParts } = await import(pathToFileURL(path.join(root, 'client/src/content/legal.js')).href);

// The server's record of the current versions (what users must accept) has to match these documents.
const serverLegal = fs.readFileSync(path.join(root, 'server/src/config/legal.ts'), 'utf8');
const serverVersion = (name) => serverLegal.match(new RegExp(`${name}:\\s*'([^']+)'`))?.[1];
const byslug = Object.fromEntries(LEGAL_DOCS.map((d) => [d.slug, d]));
for (const [name, slug] of [['terms', 'terms'], ['privacy', 'privacy']]) {
    if (serverVersion(name) !== byslug[slug].effectiveDate) {
        console.error(`LEGAL_VERSIONS.${name} in server/src/config/legal.ts is "${serverVersion(name)}" but ${slug} effectiveDate is "${byslug[slug].effectiveDate}". Make them equal.`);
        process.exit(1);
    }
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const linked = (text) =>
    linkParts(text)
        .map((p) =>
            p.type === 'text'
                ? esc(p.value)
                : p.type === 'email'
                  ? `<a href="mailto:${esc(p.value)}">${esc(p.value)}</a>`
                  : `<a href="${esc(p.value)}" rel="noreferrer">${esc(p.value)}</a>`
        )
        .join('');

function page(doc) {
    const nav = LEGAL_DOCS.map((d) => (d.slug === doc.slug ? `<strong>${esc(d.title)}</strong>` : `<a href="/${d.slug}">${esc(d.title)}</a>`)).join(' · ');
    const toc = doc.sections.map((s, i) => `<li><a href="#${s.id}">${i + 1}. ${esc(s.heading)}</a></li>`).join('');
    const sections = doc.sections
        .map((s, i) => `<section id="${s.id}">\n<h2>${i + 1}. ${esc(s.heading)}</h2>\n${s.content.split(/\n{2,}/).map((p) => `<p>${linked(p)}</p>`).join('\n')}\n</section>`)
        .join('\n');
    const extra = doc.slug === 'data-deletion' ? `<p class="cta"><a href="/data-deletion/status">Check a deletion request →</a></p>` : '';
    return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(doc.title)} | ${esc(COMPANY.product)}</title>
<meta name="description" content="${esc(doc.summary)}">
<link rel="canonical" href="${COMPANY.site}/${doc.slug}">
<!-- Generated by scripts/build-legal-html.mjs from client/src/content/legal.js. Edit that file, then rebuild. -->
<style>
  :root { color-scheme: light; --bg:#ffffff; --fg:#18181b; --muted:#52525b; --line:#e4e4e7; --accent:#18181b; }
  @media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { color-scheme: dark; --bg:#0c0c0e; --fg:#ededef; --muted:#a1a1aa; --line:#27272a; --accent:#e4e4e7; } }
  :root[data-theme="dark"] { color-scheme: dark; --bg:#0c0c0e; --fg:#ededef; --muted:#a1a1aa; --line:#27272a; --accent:#e4e4e7; }
  body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.65 system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 720px; margin: 0 auto; padding: 40px 16px 80px; }
  header { border-bottom: 1px solid var(--line); padding-bottom: 20px; margin-bottom: 24px; }
  h1 { font-size: 30px; line-height: 1.2; margin: 14px 0 8px; }
  h2 { font-size: 19px; margin: 36px 0 10px; scroll-margin-top: 16px; }
  p { margin: 0 0 14px; white-space: pre-line; overflow-wrap: anywhere; }
  nav, .meta, .toc { color: var(--muted); font-size: 14px; }
  .toc { margin: 0 0 8px; padding-left: 18px; columns: 2 220px; }
  a { color: var(--accent); }
  .cta { margin-top: 32px; font-weight: 600; }
  footer { border-top: 1px solid var(--line); margin-top: 48px; padding-top: 16px; color: var(--muted); font-size: 14px; }
</style>
</head>
<body>
<main>
<header>
  <nav><a href="/"><strong>${esc(COMPANY.product)}</strong></a> · ${nav}</nav>
  <h1>${esc(doc.title)}</h1>
  <p class="meta">${esc(COMPANY.operator)} (registration number ${esc(COMPANY.registration)}). Effective ${esc(doc.effectiveDate)}, last updated ${esc(doc.lastUpdated)}.</p>
  <ol class="toc">${toc}</ol>
</header>
${sections}
${extra}
<footer>${esc(COMPANY.operator)}, operator of ${esc(COMPANY.product)} · <a href="mailto:${COMPANY.privacyEmail}">${COMPANY.privacyEmail}</a> · <a href="${COMPANY.site}">${COMPANY.site.replace('https://', '')}</a></footer>
</main>
</body>
</html>
`;
}

const written = [];
for (const doc of LEGAL_DOCS) {
    const html = page(doc);
    const targets = [path.join(root, 'client/public', doc.slug, 'index.html'), path.join(root, 'server/public/legal', `${doc.slug}.html`)];
    for (const file of targets) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, html);
        written.push(path.relative(root, file));
    }
}
console.log(`Wrote ${written.length} files:\n  ${written.join('\n  ')}`);
